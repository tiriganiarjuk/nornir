# --- Rendering -------------------------------------------------------------

def schema_file(recipe: GateRecipe) -> str:
    """The schema's file name, from its schemas_embedded constant: PATHS_RESOLVED → paths-resolved."""
    return recipe.schema_constant.lower().replace("_", "-")


def render_lib(recipe: GateRecipe) -> str:
    paths = ", verifies that every path it names exists" if recipe.verify_paths else ""
    description = DESCRIPTIONS[recipe.kind].format(schema_file=schema_file(recipe), paths=paths)
    faces = "two faces" if recipe.kind == "input" else "its PyO3 face behind the feature \"python\""
    head = (
        f"//! Gate: {recipe.name}\n{GENERATED}//!\n//! {description}\n//!\n"
        f"//! One tool, {faces} (`NORNIR_CONVENTIONS.md` § Tool Structure): `validate` is the\n"
        f"//! tool, and each face hands its result to `tool_face_io`.\n\n"
        f"pub use gate_io::GateError;\nuse schemas_embedded::{recipe.schema_constant};\n\n"
    )
    fields = {"name": recipe.name, "schema": recipe.schema_constant, "schema_file": schema_file(recipe),
              "verify": "true" if recipe.verify_paths else "false"}
    body = BODIES[recipe.kind].format(**fields)
    return head + body + SCHEMA_NAME_FN.format(**fields) + PYMODULE.format(**fields)


def render_cargo(recipe: GateRecipe) -> str:
    extra = 'default_apply_io = { path = "../../capability/default_apply_io" }\n' if recipe.kind == "defaults" else ""
    binary = BIN.format(name=recipe.name) if recipe.kind == "input" else ""
    return CARGO.format(name=recipe.name, bin=binary, extra_dependency=extra)


def render(recipe: GateRecipe) -> dict[str, str]:
    """Every file of the gate's crate, by its path relative to the crate."""
    files = {"Cargo.toml": render_cargo(recipe), "src/lib.rs": render_lib(recipe)}
    if recipe.kind == "input":
        files["src/main.rs"] = MAIN.format(name=recipe.name)
        files["tests/cli_contract.rs"] = TEST.format(name=recipe.name, schema_file=schema_file(recipe))
    return files


# --- Writing and checking --------------------------------------------------

def write_all(recipes: GateRecipes) -> int:
    written = 0
    for recipe in recipes.gate:
        for relative, text in render(recipe).items():
            target = GATES_DIR / recipe.name / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text)
            written += 1
    return written


def differing_files(recipes: GateRecipes) -> list[str]:
    differing = []
    for recipe in recipes.gate:
        for relative, text in render(recipe).items():
            target = GATES_DIR / recipe.name / relative
            if not target.exists() or target.read_text() != text:
                differing.append(f"{recipe.name}/{relative}")
    return differing


def unlisted(recipes: GateRecipes) -> list[str]:
    """Recipes missing from the workspace or the gates deploy category, and gate directories without a recipe."""
    with open(NORNIR_DIR / "Cargo.toml", "rb") as handle:
        members = set(tomllib.load(handle)["workspace"]["members"])
    with open(NORNIR_DIR / "deploy_categories.toml", "rb") as handle:
        deployed = set(tomllib.load(handle)["gates"]["gate_crates"])
    names = {recipe.name for recipe in recipes.gate}
    problems = [f"{name}: not a workspace member" for name in sorted(names) if f"gates/{name}" not in members]
    problems += [f"{name}: not in deploy_categories.toml [gates]" for name in sorted(names - deployed)]
    directories = {path.name for path in GATES_DIR.iterdir() if path.is_dir()}
    problems += [f"gates/{name}: a gate directory with no recipe" for name in sorted(directories - names)]
    return problems


def main() -> int:
    """Write or check every gate crate; the exit code is 1 when any problem is found."""
    parser = argparse.ArgumentParser(description="Make every gate crate from its recipe.")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 on any difference")
    arguments = parser.parse_args()

    recipes = read_recipes()
    problems = unlisted(recipes)
    if arguments.check:
        problems += [f"{path}: differs from its recipe" for path in differing_files(recipes)]
        summary = f"{len(recipes.gate)} recipes checked"
    else:
        summary = f"{write_all(recipes)} files written for {len(recipes.gate)} gates"
    for problem in problems:
        logger.error(problem)
    logger.info("{}; {} problem(s)", summary, len(problems))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
