"""Make every gate crate from its recipe in gates/gate_recipes.toml.

A gate is a generated variant (HOW_A_NORNIR_TOOL_IS_MADE.md): the read and write
engines with a schema embedded and the format fixed to TOML. Its recipe — name,
kind, schema, whether paths are verified — is the one place it is described; the
crate is computed from it. The recipes are read through read_toml_validate_json
against schemas/tools/gate-recipes.schema.json.

Usage:
    generate_gates.py            write every gate crate from its recipe
    generate_gates.py --check    write nothing; exit 1 naming every crate that differs
                                 from its recipe, every recipe missing from the workspace
                                 or from deploy_categories.toml, and every gates/ directory
                                 without a recipe

Writes, per gate: Cargo.toml and src/lib.rs; for an input gate also src/main.rs and
tests/cli_contract.rs, its CLI face.
"""

import argparse
import json
import subprocess
import sys
import tomllib
from pathlib import Path
from typing import Literal

from loguru import logger
from pydantic import BaseModel, ConfigDict, Field

NORNIR_DIR = Path(__file__).resolve().parent
GATES_DIR = NORNIR_DIR / "gates"
RECIPES = GATES_DIR / "gate_recipes.toml"
SCHEMA_DIR = NORNIR_DIR / "schemas" / "tools"
TOML_READER = Path.home() / "ai" / "tools" / "bin" / "read_toml_validate_json"


class GateRecipe(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    name: str
    kind: Literal["input", "output", "passthrough", "defaults"]
    # The recipe's `schema` key: the schemas_embedded constant the gate embeds.
    schema_constant: str = Field(alias="schema")
    verify_paths: bool | None = None


class GateRecipes(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    gate: tuple[GateRecipe, ...]


# --- Recipes ---------------------------------------------------------------

def read_recipes() -> GateRecipes:
    """The recipes, validated by nornir's TOML reader. Exits on a refusal."""
    result = subprocess.run(
        [str(TOML_READER), str(RECIPES), "gate-recipes", str(SCHEMA_DIR)],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        logger.error("{} refused {}:\n{}", TOML_READER.name, RECIPES, result.stderr)
        sys.exit(1)
    return GateRecipes.model_validate_json(result.stdout)


